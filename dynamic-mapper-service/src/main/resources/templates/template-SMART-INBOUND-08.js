/**
 * @name SparkPlugB DDATA/NDATA decoder
 * @description Decodes a SparkPlugB protobuf payload received via the ANY_PAYLOAD mapping type.
 *              msg.payload is a Base64-encoded binary string containing the serialised
 *              sparkplug_b.proto Payload message. Each numeric or boolean metric is mapped
 *              to a fragment/series in a single Cumulocity measurement. String metrics are
 *              emitted as events. The device is identified by the edge-node-id (and optional
 *              device-id) extracted from the SparkPlugB topic.
 *              Base64 decoding is done in pure ECMAScript (no Java interop required).
 * @templateType INBOUND_SMART_FUNCTION
 * @defaultTemplate false
 * @internal true
 * @readonly true
 *
 * Requires:
 *   MappingType  : ANY_PAYLOAD
 *   Topic pattern: spBv1.0/+/DDATA/+/+  or  spBv1.0/+/NDATA/+
 *
 * SparkPlugB Payload proto (sparkplug_b.proto — abridged):
 *   message Payload {
 *     uint64          timestamp = 1;
 *     repeated Metric metrics  = 2;
 *     uint64          seq      = 3;
 *   }
 *   message Metric {
 *     string name      = 1;   uint64 alias     = 2;   uint64 timestamp = 3;
 *     uint32 datatype  = 4;   bool   is_null   = 7;
 *     oneof value {
 *       uint32 int_value     = 10;   uint64 long_value   = 11;
 *       float  float_value   = 12;   double double_value = 13;
 *       bool   boolean_value = 14;   string string_value = 15;
 *     }
 *   }
 *
 * SparkPlugB DataType enum (relevant subset):
 *   Int8=1  Int16=2  Int32=3  Int64=4  UInt8=5  UInt16=6  UInt32=7  UInt64=8
 *   Float=9  Double=10  Boolean=11  String=12  DateTime=13
 *
 * Sample topic  : spBv1.0/factory-01/DDATA/edge-node-01/device-01
 * Sample payload: generated by SparkplugBMqttTestClient.java
 */

// ─────────────────────────────────────────────────────────────────────────────
// Base64 → Uint8Array  (pure ECMAScript, no Java interop, no browser APIs)
// ─────────────────────────────────────────────────────────────────────────────

function decodeBase64ToBytes(b64) {
    // Build a 256-entry lookup table from the Base64 alphabet once per call.
    // (A module-level constant would be ideal but this function is self-contained
    //  so it works whether the script runs as a module or a plain script.)
    var ALPHA = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
    var lookup = new Uint8Array(256);
    for (var i = 0; i < 64; i++) {
        lookup[ALPHA.charCodeAt(i)] = i;
    }

    // Strip trailing '=' padding before computing output length.
    var stripped = b64.replace(/=+$/, '');
    var inLen    = stripped.length;
    var outLen   = (inLen * 3) >>> 2;   // same as Math.floor(inLen * 3 / 4)
    var out      = new Uint8Array(outLen);
    var p        = 0;

    for (var i = 0; i < inLen; i += 4) {
        var e1 = lookup[stripped.charCodeAt(i)];
        var e2 = lookup[stripped.charCodeAt(i + 1)];
        var e3 = i + 2 < inLen ? lookup[stripped.charCodeAt(i + 2)] : 0;
        var e4 = i + 3 < inLen ? lookup[stripped.charCodeAt(i + 3)] : 0;

        out[p++] = (e1 << 2) | (e2 >> 4);
        if (p < outLen) out[p++] = ((e2 & 0xF) << 4) | (e3 >> 2);
        if (p < outLen) out[p++] = ((e3 & 0x3) << 6) | e4;
    }
    return out;
}

// ─────────────────────────────────────────────────────────────────────────────
// Minimal Protobuf binary reader
// Covers every wire type used by sparkplug_b.proto.
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Read a protobuf varint from bytes[pos].
 * Accurate to 53-bit precision (JS Number safe integer limit).
 * @returns {{ value: number, nextPos: number }}
 */
function readVarint(bytes, pos) {
    var result = 0;
    var shift  = 0;
    while (pos < bytes.length) {
        var b = bytes[pos++];
        result += (b & 0x7F) * Math.pow(2, shift);
        if ((b & 0x80) === 0) break;
        shift += 7;
    }
    return { value: result, nextPos: pos };
}

/**
 * Read a little-endian 32-bit IEEE 754 float starting at bytes[pos].
 * @returns {{ value: number, nextPos: number }}
 */
function readFloat(bytes, pos) {
    var buf  = new ArrayBuffer(4);
    var view = new DataView(buf);
    view.setUint8(0, bytes[pos]);
    view.setUint8(1, bytes[pos + 1]);
    view.setUint8(2, bytes[pos + 2]);
    view.setUint8(3, bytes[pos + 3]);
    return { value: view.getFloat32(0, /*littleEndian=*/true), nextPos: pos + 4 };
}

/**
 * Read a little-endian 64-bit IEEE 754 double starting at bytes[pos].
 * @returns {{ value: number, nextPos: number }}
 */
function readDouble(bytes, pos) {
    var buf  = new ArrayBuffer(8);
    var view = new DataView(buf);
    for (var i = 0; i < 8; i++) view.setUint8(i, bytes[pos + i]);
    return { value: view.getFloat64(0, /*littleEndian=*/true), nextPos: pos + 8 };
}

/**
 * Read a length-delimited field (protobuf wire type 2).
 * @returns {{ data: Uint8Array, nextPos: number }}
 */
function readLengthDelimited(bytes, pos) {
    var r   = readVarint(bytes, pos);
    var len = r.value;
    var start = r.nextPos;
    return { data: bytes.slice(start, start + len), nextPos: start + len };
}

/** Decode a UTF-8 Uint8Array to a JS string. */
function bytesToString(bytes) {
    var str = '';
    for (var i = 0; i < bytes.length; ) {
        var b = bytes[i++];
        if (b < 0x80) {
            str += String.fromCharCode(b);
        } else if ((b & 0xE0) === 0xC0) {
            str += String.fromCharCode(((b & 0x1F) << 6) | (bytes[i++] & 0x3F));
        } else if ((b & 0xF0) === 0xE0) {
            str += String.fromCharCode(((b & 0x0F) << 12) | ((bytes[i++] & 0x3F) << 6) | (bytes[i++] & 0x3F));
        } else {
            i += 3; // 4-byte supplementary plane — skip (metric names rarely use emoji)
        }
    }
    return str;
}

// ─────────────────────────────────────────────────────────────────────────────
// sparkplug_b.proto parsers
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Parse one Metric message from bytes[start..end].
 * @returns {{ name, alias, timestamp, datatype, value, isNull }}
 */
function parseMetric(bytes, start, end) {
    var m   = { name: null, alias: null, timestamp: null, datatype: null, value: null, isNull: false };
    var pos = start;

    while (pos < end) {
        var tagR   = readVarint(bytes, pos);
        pos        = tagR.nextPos;
        var tag    = tagR.value;
        var field  = tag >>> 3;
        var wire   = tag & 0x07;
        var r;

        switch (field) {
            case 1:  r = readLengthDelimited(bytes, pos); m.name      = bytesToString(r.data); pos = r.nextPos; break;
            case 2:  r = readVarint(bytes, pos);          m.alias     = r.value;               pos = r.nextPos; break;
            case 3:  r = readVarint(bytes, pos);          m.timestamp = r.value;               pos = r.nextPos; break;
            case 4:  r = readVarint(bytes, pos);          m.datatype  = r.value;               pos = r.nextPos; break;
            case 5:  // is_historical — skip
            case 6:  r = readVarint(bytes, pos);                                               pos = r.nextPos; break;
            case 7:  r = readVarint(bytes, pos);          m.isNull    = r.value !== 0;         pos = r.nextPos; break;
            case 8:  // metadata
            case 9:  r = readLengthDelimited(bytes, pos);                                      pos = r.nextPos; break;
            case 10: r = readVarint(bytes, pos);          m.value     = r.value;               pos = r.nextPos; break; // int_value
            case 11: r = readVarint(bytes, pos);          m.value     = r.value;               pos = r.nextPos; break; // long_value
            case 12: r = readFloat(bytes, pos);           m.value     = r.value;               pos = r.nextPos; break; // float_value
            case 13: r = readDouble(bytes, pos);          m.value     = r.value;               pos = r.nextPos; break; // double_value
            case 14: r = readVarint(bytes, pos);          m.value     = r.value !== 0;         pos = r.nextPos; break; // boolean_value
            case 15: r = readLengthDelimited(bytes, pos); m.value     = bytesToString(r.data); pos = r.nextPos; break; // string_value
            case 16: // bytes_value
            case 17: // dataset_value
            case 18: r = readLengthDelimited(bytes, pos);                                      pos = r.nextPos; break;
            default:
                if      (wire === 0) { r = readVarint(bytes, pos);          pos = r.nextPos; }
                else if (wire === 2) { r = readLengthDelimited(bytes, pos); pos = r.nextPos; }
                else if (wire === 1) { pos += 8; }
                else if (wire === 5) { pos += 4; }
                else                 { pos = end; } // unrecognised — bail
        }
    }
    return m;
}

/**
 * Parse a full sparkplug_b.proto Payload from a Uint8Array.
 * @returns {{ timestamp: number|null, seq: number|null, metrics: Array }}
 */
function parseSparkplugPayload(bytes) {
    var result = { timestamp: null, seq: null, metrics: [] };
    var pos    = 0;

    while (pos < bytes.length) {
        var tagR  = readVarint(bytes, pos);
        pos       = tagR.nextPos;
        var tag   = tagR.value;
        var field = tag >>> 3;
        var wire  = tag & 0x07;
        var r;

        switch (field) {
            case 1: r = readVarint(bytes, pos);          result.timestamp = r.value;                                 pos = r.nextPos; break;
            case 2: r = readLengthDelimited(bytes, pos); result.metrics.push(parseMetric(r.data, 0, r.data.length)); pos = r.nextPos; break;
            case 3: r = readVarint(bytes, pos);          result.seq       = r.value;                                 pos = r.nextPos; break;
            default:
                if      (wire === 0) { r = readVarint(bytes, pos);          pos = r.nextPos; }
                else if (wire === 2) { r = readLengthDelimited(bytes, pos); pos = r.nextPos; }
                else if (wire === 1) { pos += 8; }
                else if (wire === 5) { pos += 4; }
                else                 { pos = bytes.length; }
        }
    }
    return result;
}

// ─────────────────────────────────────────────────────────────────────────────
// SparkPlugB topic helpers
// spBv1.0/<groupId>/<msgType>/<edgeNodeId>[/<deviceId>]
// ─────────────────────────────────────────────────────────────────────────────

function parseSparkplugTopic(topic) {
    var parts = topic.split('/');
    if (parts.length < 4) return null;
    return {
        groupId    : parts[1],
        messageType: parts[2],
        edgeNodeId : parts[3],
        deviceId   : parts.length >= 5 ? parts[4] : null
    };
}

/** Derive external ID: "<edgeNode>/<device>" for DDATA, "<edgeNode>" for NDATA. */
function getExternalId(parsed) {
    return parsed.deviceId
        ? parsed.edgeNodeId + '/' + parsed.deviceId
        : parsed.edgeNodeId;
}

// ─────────────────────────────────────────────────────────────────────────────
// Metric name → C8Y fragment / series
// "Inputs/Temperature" → fragment="Inputs", series="Temperature"
// "temperature"        → fragment="c8y_SparkplugMetrics", series="temperature"
// ─────────────────────────────────────────────────────────────────────────────

function sanitise(s) { return s.replace(/[^a-zA-Z0-9_]/g, '_'); }

function toC8yName(metricName) {
    var parts  = metricName.split('/');
    var series = sanitise(parts[parts.length - 1]);
    var fragment = parts.length > 1
        ? sanitise(parts.slice(0, -1).join('_'))
        : 'c8y_SparkplugMetrics';
    return { fragment: fragment, series: series };
}

// ─────────────────────────────────────────────────────────────────────────────
// Smart Function entry point
// ─────────────────────────────────────────────────────────────────────────────

function onMessage(msg, context) {

    // 1 ── Decode Base64 → raw bytes ────────────────────────────────────────
    var base64 = msg.payload;
    if (!base64 || typeof base64 !== 'string') {
        console.log("Expected Base64 string from ANY_PAYLOAD mapping, got: " + typeof base64);
        return [];
    }

    var bytes;
    try {
        bytes = decodeBase64ToBytes(base64);
    } catch (e) {
        console.log("Base64 decode failed: " + e);
        return [];
    }
    console.log("Decoded " + bytes.length + " bytes");

    // 2 ── Parse SparkPlugB protobuf ────────────────────────────────────────
    var spPayload;
    try {
        spPayload = parseSparkplugPayload(bytes);
    } catch (e) {
        console.log("SparkPlugB parse error: " + e);
        return [];
    }
    console.log("SparkPlugB seq=" + spPayload.seq + " metrics=" + spPayload.metrics.length);

    if (spPayload.metrics.length === 0) {
        console.log("No metrics — nothing to map");
        return [];
    }

    // 3 ── Extract device identity from topic ───────────────────────────────
    var topic  = msg.topic;
    var parsed = parseSparkplugTopic(topic);
    if (!parsed) {
        console.log("Cannot parse SparkPlugB topic: " + topic);
        return [];
    }
    var externalId = getExternalId(parsed);
    console.log("externalId=" + externalId + " group=" + parsed.groupId + " msgType=" + parsed.messageType);

    // 4 ── Determine measurement timestamp ─────────────────────────────────
    var isoTime = spPayload.timestamp
        ? new Date(spPayload.timestamp).toISOString()
        : new Date().toISOString();

    // 5 ── Build C8Y outputs ────────────────────────────────────────────────
    var output = [];

    // Measurement payload — collects all numeric / boolean metrics
    var measurementPayload = { time: isoTime, type: "c8y_SparkplugMeasurement" };
    var hasNumeric = false;

    for (var i = 0; i < spPayload.metrics.length; i++) {
        var metric = spPayload.metrics[i];
        var label  = metric.name || ('alias_' + metric.alias) || ('metric_' + i);

        if (metric.isNull || metric.value === null || metric.value === undefined) {
            console.log("Skip null metric: " + label);
            continue;
        }

        var isNumeric = typeof metric.value === 'number';
        var isBool    = typeof metric.value === 'boolean';
        var isString  = typeof metric.value === 'string';

        if (isNumeric || isBool) {
            // Map to measurement fragment
            var names = toC8yName(label);
            if (!measurementPayload[names.fragment]) {
                measurementPayload[names.fragment] = {};
            }
            measurementPayload[names.fragment][names.series] = {
                value: isBool ? (metric.value ? 1 : 0) : metric.value,
                unit : ""
            };
            console.log("Metric (numeric): " + label + " = " + metric.value + " (datatype=" + metric.datatype + ")");
            hasNumeric = true;

        } else if (isString) {
            // Emit a separate event for string metrics (e.g. firmware version, status text)
            output.push({
                cumulocityType: "event",
                action        : "create",
                payload: {
                    time  : metric.timestamp ? new Date(metric.timestamp).toISOString() : isoTime,
                    type  : "c8y_SparkplugStringMetric",
                    text  : label + " = " + metric.value,
                    c8y_SparkplugMetric: { name: label, value: metric.value }
                },
                externalSource: [{ type: "c8y_Serial", externalId: externalId }]
            });
            console.log("Metric (string): " + label + " = " + metric.value);
        }
    }

    // Add measurement only if at least one numeric/boolean metric was found
    if (hasNumeric) {
        output.push({
            cumulocityType: "measurement",
            action        : "create",
            payload       : measurementPayload,
            externalSource: [{ type: "c8y_Serial", externalId: externalId }],
            contextData   : {
                deviceName: externalId,
                deviceType: "SparkplugEdgeNode"
            }
        });
    }

    console.log("Emitting " + output.length + " C8Y object(s)");
    return output;
}

export {onMessage};
