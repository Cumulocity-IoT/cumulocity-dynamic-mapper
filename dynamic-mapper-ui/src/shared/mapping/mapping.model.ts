export interface StepperConfiguration {
  showEditorSource?: boolean;
  showEditorTarget?: boolean;
  showProcessorExtensionsSource?: boolean;
  showProcessorExtensionsTarget?: boolean;
  showProcessorExtensionsInternal?: boolean;
  showCodeEditor?: boolean;
  showFilterExpression?: boolean;
  /** How Save persists the mapping; see {@link MappingPersistence}. */
  persistence?: MappingPersistence;
  /** Disables every editing control (deprecated mappings, users without a manage role). */
  readOnly?: boolean;
  /** The mapping being created is a copy of an existing one, so its templates are kept rather
   *  than replaced by the generic defaults. */
  isCopy?: boolean;
  allowNoDefinedIdentifier?: boolean;
  allowDefiningSubstitutions?: boolean;
  allowTestTransformation?: boolean;
  allowTestSending?: boolean;
  direction?: Direction;
  /** Section to advance from straight to the last one, in the base numbering (`STEP_*` in
   *  stepper.model.ts, without the outbound-only Subscription section). Editors map it through
   *  `StepLayout.fromBase`. */
  advanceFromStepToEndStep?: number;
  allowTemplateExpansion?: boolean;  // Whether to allow template expansion with sample data
  /** One-shot flag: auto-launch AI generation (Smart Function code or JSONata substitutions)
   *  once the transformation step is first reached. */
  triggerAIGenerationOnStart?: boolean;
  /** Outbound only: type, groups and device of the Message Explorer message this mapping was
   *  created from, offered as one-click choices in the Subscription step. */
  subscriptionSuggestions?: SubscriptionSuggestions;
  /** Transport fields observed on the message this mapping was created from (e.g. a Kafka record
   *  key). Smart Functions and Java extensions receive these out-of-band via `msg.transportFields`
   *  rather than in the payload, so they cannot be conveyed through the source template — this
   *  carries them to AI generation as an example of what the mapping will see at runtime. */
  sampleTransportFields?: Record<string, string>;
  /** What is known about the captured message the sample comes from (payload type/size/format,
   *  sender client ID); carried to AI generation, see {@link SampleMessageInfo}. */
  sampleMessageInfo?: SampleMessageInfo;
  /** Further captured messages of the same payload type as the primary sample (Message Explorer
   *  multi-select). Stepper state only, never persisted: used solely to give AI generation more
   *  than one example so it can generalize (optional fields, varying array lengths). */
  additionalSamples?: AdditionalSample[];
}

/** One extra sample message handed to AI generation, see {@link StepperConfiguration.additionalSamples}. */
export interface AdditionalSample {
  /** Concrete topic the message was received on. */
  topic: string;
  /** Sample in the same shape as the mapping's sourceTemplate (JSON text; raw payloads wrapped as {"payload": ...}). */
  payload: string;
  transportFields?: Record<string, string>;
}

export enum TransformationType {
  /** @deprecated Legacy substitution engine, superseded by JSONata. Kept for backward compatibility
   *  with existing mappings and as the only supported transformation for Protobuf (internal) payloads.
   *  New mappings should use {@link TransformationType.JSONATA} instead. */
  DEFAULT = 'DEFAULT',
  /** @deprecated removed in 6.3.0 — existing mappings are read-only and can only be exported or deleted. */
  SUBSTITUTION_AS_CODE = 'SUBSTITUTION_AS_CODE',
  SMART_FUNCTION = 'SMART_FUNCTION',
  JSONATA = 'JSONATA',
  EXTENSION_JAVA = 'EXTENSION_JAVA',
}

export type SamplePayloadType = 'EMPTY' | 'JSON' | 'XML' | 'TEXT' | 'BINARY';

/** Facts about the real message a mapping's sample was captured from (Message Explorer). Kept as
 *  stepper state only, never persisted on the mapping. Sent to AI generation so the agent does not
 *  have to guess from the sample how to read the message. */
export interface SampleMessageInfo {
  payloadType?: SamplePayloadType;
  /** Well-known binary container recognized by magic bytes (e.g. GZIP); absent if unknown. */
  binaryFormat?: string;
  /** Size of the raw message in bytes. */
  payloadSize?: number;
  /** Client ID of the sender; delivered at runtime as msg.clientId. */
  clientId?: string;
  /** Concrete topic the message was received on. */
  topic?: string;
  /** Type of the connector the message was captured on (e.g. MQTT, KAFKA, PULSAR); inbound only. */
  connectorType?: string;
}

